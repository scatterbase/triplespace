#!/usr/bin/env python3
"""Generates docs/registry/sites.toml, the default site aliases (0026 §2; 0110 §4), from
Wikimedia's site matrix (meta.wikimedia.org, action=sitematrix).

  python3 tools/sites_gen.py                    # fetch the matrix, rewrite the file
  python3 tools/sites_gen.py --from matrix.json # use a saved response instead of fetching
  python3 tools/sites_gen.py --check            # exit 1 if the file is not what the matrix gives
  python3 tools/sites_gen.py --save matrix.json # also keep the response that was used

One `[[site]]` per wiki the matrix lists, sorted by site ID, with these rules:

  id        the wiki's database name (`dbname`), which is its MediaWiki global site ID
  host      the host of the matrix's `url`, lowercased; it must already be an ASCII domain key
  path      `/wiki/$1`: every Wikimedia wiki uses it
  language  the site's `lang`, or the language entry's code when the site carries none
  group     the project family of a language site (`wiki` is written `wikipedia`), and
            `special` for every entry of the matrix's `specials` list

Private wikis are left out: nothing on them can be read or linked from outside. Closed and
fishbowl wikis are kept, because their pages and revisions are still public and citable.

The file's header comment and `generated_from` are written by this script. `generated_at` is
the UTC date of the run; --check ignores it, so a check on another day passes. The file is
committed (24 §11): run this, read the diff, and commit the result. Only the standard library
is used, and Python 3.10 is enough.

Wikimedia asks automated clients to send a descriptive User-Agent and throttles those that
do not (HTTP 429); --user-agent overrides the default. maxlag=5 is sent, and a 429 or a
maxlag error is retried up to four times, honouring Retry-After.
"""
import argparse
import datetime
import json
import pathlib
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "registry" / "sites.toml"

API = "https://meta.wikimedia.org/w/api.php"
QUERY = {
    "action": "sitematrix",
    "format": "json",
    "formatversion": "2",
    "smsiteprop": "url|dbname|code|lang",
    "smlangprop": "code|site",
    "maxlag": "5",
}
SOURCE = API + "?action=sitematrix"
USER_AGENT = "triplespace-sites-gen/1.0 (https://github.com/scatterbase/triplespace)"
PATH = "/wiki/$1"

DBNAME = re.compile(r"[a-z][a-z0-9_]*")
HOST_LABEL = re.compile(r"[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?")

HEADER = """\
# Site aliases.  ADR 0026 §2; generated by tools/sites_gen.py (0110 §4). Do not edit by hand.
#
# A sitelink is a URL and its site ID is its host (0026 §2). A site alias gives a host the
# MediaWiki site ID, article path and language that Wikidata tooling expects, so that
# `enwiki` + `Douglas Adams` and https://en.wikipedia.org/wiki/Douglas_Adams are one sitelink.
# There is no site table: an alias exists only for compatibility, and a host without one is
# linked by URL with the host as its site ID. The same entries give a `wikimedia` key's
# database name its host, for the link to the page or revision (0110 §3); a key does not
# depend on them.
#
# Every public wiki in Wikimedia's site matrix (API:Sitematrix) is listed, closed and
# fishbowl wikis included and private wikis left out. To refresh it, run
# `python3 tools/sites_gen.py`, read the diff and commit it. A tenant adds aliases for other
# MediaWiki hosts as config records of kind `site-alias`.
#
# id         MediaWiki site ID (the global ID in the sites table): the wiki's database name.
# host       The host, as a Domain key (0009 §2).
# path       Article path with $1 for the title.
# language   Content language, for schema:inLanguage.
# group      MediaWiki site group, informational: the project family, or `special`.
"""


def fetch(user_agent: str) -> dict:
    url = API + "?" + urllib.parse.urlencode(QUERY)
    request = urllib.request.Request(url, headers={"User-Agent": user_agent})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                data = json.load(response)
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 4:
                raise
            wait = int(e.headers.get("Retry-After") or 5 * 2**attempt)
        else:
            if data.get("error", {}).get("code") != "maxlag" or attempt == 4:
                return data
            wait = 5 * 2**attempt
        print(f"throttled; retrying in {wait}s", file=sys.stderr)
        time.sleep(wait)
    raise AssertionError("unreachable")


def host_of(url: str, dbname: str) -> str:
    parts = urllib.parse.urlsplit(url)
    host = (parts.hostname or "").lower()
    labels = host.split(".")
    if parts.scheme != "https" or len(labels) < 2 or not all(HOST_LABEL.fullmatch(l) for l in labels):
        raise SystemExit(f"{dbname}: `{url}` does not have an https URL with an ASCII domain host")
    return host


def sites(matrix: dict) -> list[dict]:
    if "sitematrix" not in matrix:
        raise SystemExit(f"not a site matrix response: {json.dumps(matrix)[:200]}")
    out = []
    for key, entry in matrix["sitematrix"].items():
        if key == "count":
            continue
        special = key == "specials"
        for s in entry if special else entry["site"]:
            if "private" in s:
                continue
            dbname = s["dbname"]
            if not DBNAME.fullmatch(dbname):
                raise SystemExit(f"`{dbname}` is not a database name this file accepts")
            group = "special" if special else ("wikipedia" if s["code"] == "wiki" else s["code"])
            language = s.get("lang") or (None if special else entry["code"])
            out.append(
                {
                    "id": dbname,
                    "host": host_of(s["url"], dbname),
                    "path": PATH,
                    "language": language,
                    "group": group,
                }
            )
    out.sort(key=lambda s: s["id"])
    for what in ("id", "host"):
        seen = {}
        for s in out:
            if s[what] in seen:
                raise SystemExit(f"`{seen[s[what]]}` and `{s['id']}` share the {what} `{s[what]}`")
            seen[s[what]] = s["id"]
    return out


def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(entries: list[dict], date: str) -> str:
    lines = [
        HEADER,
        "version = 1",
        f"generated_from = {quote(SOURCE)}",
        f"generated_at = {quote(date)}",
    ]
    for s in entries:
        lines.append("")
        lines.append("[[site]]")
        for field in ("id", "host", "path", "language", "group"):
            if s[field] is not None:
                lines.append(f"{field} = {quote(s[field])}")
    return "\n".join(lines) + "\n"


def without_date(text: str) -> str:
    return re.sub(r'(?m)^generated_at = .*$', "", text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from", dest="source", type=pathlib.Path, help="a saved sitematrix JSON response")
    parser.add_argument("--save", type=pathlib.Path, help="write the response used to this file")
    parser.add_argument("--out", type=pathlib.Path, default=TARGET, help="default: docs/registry/sites.toml")
    parser.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on a difference")
    parser.add_argument("--user-agent", default=USER_AGENT)
    args = parser.parse_args()

    matrix = json.loads(args.source.read_text()) if args.source else fetch(args.user_agent)
    if args.save:
        args.save.write_text(json.dumps(matrix, ensure_ascii=False))
    entries = sites(matrix)
    text = render(entries, datetime.datetime.now(datetime.timezone.utc).date().isoformat())

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if without_date(current) != without_date(text):
            print(f"{args.out} is not what the site matrix gives; run tools/sites_gen.py", file=sys.stderr)
            return 1
        print(f"{args.out}: {len(entries)} sites, current")
        return 0
    args.out.write_text(text)
    print(f"{args.out}: {len(entries)} sites")
    return 0


if __name__ == "__main__":
    sys.exit(main())
