//! The namespace registry (0008 §1; 10 §1), embedding `docs/registry/namespaces.toml`.
//!
//! This is the registry half of the crate 22 §2.1 describes; the special-page registry
//! and title normalization join it as their callers are built. A namespace's local name
//! can differ from its canonical one (Project follows the site's name, 0008 A37): that is
//! tenant configuration, which callers apply on top.

#![forbid(unsafe_code)]

use std::sync::OnceLock;

use serde::Deserialize;

/// The registry file, as embedded.
pub const NAMESPACES_TOML: &str = include_str!("../../../docs/registry/namespaces.toml");

/// The Project namespace's number.
pub const PROJECT: i32 = 4;
/// The Interface namespace's number: MediaWiki's, whose canonical name it keeps (0095 §1).
pub const INTERFACE: i32 = 8;
/// The Template namespace's number.
pub const TEMPLATE: i32 = 10;

/// Whether a namespace holds pages (0041 §4).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// It holds pages, of the models it names.
    Pages,
    /// Listed, holding none.
    Reserved,
    /// Generated by the server (`Special`, `Media`).
    Virtual,
    /// Titles resolve through a resolver to entities (0029).
    Resolver,
}

/// One namespace.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct Namespace {
    /// Its number.
    pub id: i32,
    /// Its canonical name; empty for the main namespace.
    pub canonical: String,
    /// The local name every tenant shows, where it is not the canonical one (0095 §1).
    #[serde(default)]
    pub name: Option<String>,
    /// Whether it holds pages.
    pub kind: Kind,
    /// The models its pages may have.
    #[serde(default)]
    pub content_models: Vec<String>,
    /// The model a new page takes.
    #[serde(default)]
    pub default_model: Option<String>,
    /// The title normalizer (`first-letter`, `entity-id`, …).
    #[serde(default)]
    pub normalizer: Option<String>,
    /// What `meta=siteinfo` reports as its case.
    #[serde(default)]
    pub case: Option<String>,
    /// Whether `/` makes subpages.
    #[serde(default)]
    pub subpages: bool,
    /// Its talk namespace.
    #[serde(default)]
    pub talk: Option<i32>,
    /// The `site` setting that turns it on, while it is otherwise reserved.
    #[serde(default)]
    pub enabled_by: Option<String>,
}

impl Namespace {
    /// Whether its pages may have a model.
    #[must_use]
    pub fn allows_model(&self, model: &str) -> bool {
        self.content_models.iter().any(|m| m == model)
    }

    /// Whether it holds pages, given whether its enabling setting is on.
    #[must_use]
    pub fn holds_pages(&self, enabled: impl Fn(&str) -> bool) -> bool {
        self.kind == Kind::Pages && self.enabled_by.as_deref().is_none_or(enabled)
    }

    /// Whether its pages are entities (a `wikibase-*` or other entity model), whose links
    /// name the entity rather than a page: Item and Property by their ID, and the keyed
    /// types' namespaces (Domain, Keyword, Notation) by their key.
    #[must_use]
    pub fn is_entity_namespace(&self) -> bool {
        self.normalizer.as_deref() == Some("entity-id")
            || self
                .default_model
                .as_deref()
                .and_then(|m| scatter_pages::ContentModels::embedded().get(m))
                .is_some_and(|m| m.source == Some(scatter_pages::ModelSource::Entity))
    }

    /// The entity a title in this namespace names, by its ID: the title itself under the
    /// `entity-id` normalizer (`Q5`), `{keyed type}:{key}` in a keyed type's namespace
    /// (`domain:wikipedia.org`), whose normalizer is named for the type; `None` outside the
    /// entity namespaces.
    #[must_use]
    pub fn entity_id(&self, text: &str) -> Option<String> {
        if !self.is_entity_namespace() {
            return None;
        }
        match self.normalizer.as_deref() {
            Some("entity-id") | None => Some(text.to_string()),
            Some(keyed) => Some(format!("{keyed}:{text}")),
        }
    }
}

#[derive(Deserialize)]
struct File {
    namespace: Vec<Namespace>,
}

/// The registry.
#[derive(Debug, Clone)]
pub struct Namespaces {
    rows: Vec<Namespace>,
}

impl Namespaces {
    /// The embedded registry.
    ///
    /// # Panics
    ///
    /// If the embedded file does not parse, which its test rules out.
    #[must_use]
    pub fn embedded() -> &'static Namespaces {
        static R: OnceLock<Namespaces> = OnceLock::new();
        R.get_or_init(|| Self::parse(NAMESPACES_TOML).expect("the embedded registry parses"))
    }

    /// Parses a registry file.
    pub fn parse(text: &str) -> Result<Self, toml::de::Error> {
        let f: File = toml::from_str(text)?;
        Ok(Self { rows: f.namespace })
    }

    /// A namespace by number.
    #[must_use]
    pub fn get(&self, id: i32) -> Option<&Namespace> {
        self.rows.iter().find(|n| n.id == id)
    }

    /// A namespace by canonical name, ignoring case and treating `_` as a space.
    #[must_use]
    pub fn by_name(&self, name: &str) -> Option<&Namespace> {
        let want = name.replace('_', " ").trim().to_lowercase();
        self.rows
            .iter()
            .find(|n| n.canonical.to_lowercase() == want)
    }

    /// Every namespace, in registry order.
    pub fn iter(&self) -> impl Iterator<Item = &Namespace> {
        self.rows.iter()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_embedded_registry_parses() {
        let r = Namespaces::embedded();
        let project = r.get(PROJECT).expect("Project");
        assert_eq!(project.canonical, "Project");
        assert!(project.allows_model("wikitext"));
        assert!(project.holds_pages(|_| false));
        let template = r.get(TEMPLATE).expect("Template");
        assert!(
            template.holds_pages(|_| false),
            "templates are part of wikitext"
        );
        let module = r.get(828).expect("Module");
        assert!(!module.holds_pages(|_| false));
        assert!(module.holds_pages(|s| s == "wikitext.lua"));
        assert!(!r.get(3).expect("User talk").allows_model("wikitext"));
        assert!(r.get(120).expect("Item").is_entity_namespace());
        let domain = r.get(210).expect("Domain");
        assert!(
            domain.is_entity_namespace(),
            "a keyed type's pages are entities"
        );
        assert_eq!(
            domain.entity_id("wikipedia.org").as_deref(),
            Some("domain:wikipedia.org")
        );
        assert_eq!(r.get(120).unwrap().entity_id("Q5").as_deref(), Some("Q5"));
        assert_eq!(r.get(4).unwrap().entity_id("Home"), None);
        assert!(!r.get(4).unwrap().is_entity_namespace());
        assert_eq!(r.by_name("user_talk").map(|n| n.id), Some(3));
        let interface = r.get(8).unwrap();
        assert_eq!(interface.kind, Kind::Pages);
        assert_eq!(interface.canonical, "MediaWiki");
        assert_eq!(interface.name.as_deref(), Some("Interface"));
        assert_eq!(interface.talk, Some(9));
        assert_eq!(r.get(12).map(|n| n.kind), Some(Kind::Reserved));
    }
}
