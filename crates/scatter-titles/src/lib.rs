//! The namespace registry (0008 §1; 10 §1), embedding `docs/registry/namespaces.toml`.
//!
//! This is the registry half of the crate 22 §2.1 describes, with the special-page
//! registry in [`special`]; title normalization joins it as its callers are built. A namespace's local name
//! can differ from its canonical one (Project follows the site's name, 0008 A37): that is
//! tenant configuration, which callers apply on top.

#![forbid(unsafe_code)]

pub mod special;

use std::sync::OnceLock;

use serde::Deserialize;

/// The registry file, as embedded.
pub const NAMESPACES_TOML: &str = include_str!("../../../docs/registry/namespaces.toml");

/// The Project namespace's number.
pub const PROJECT: i32 = 4;
/// The Interface namespace's number: MediaWiki's, whose canonical name it keeps (0095 §1).
pub const INTERFACE: i32 = 8;
/// The Template namespace's number.
pub const TEMPLATE: i32 = 10;

/// Whether a namespace holds pages (0041 §4).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// It holds pages, of the models it names.
    Pages,
    /// Listed, holding none.
    Reserved,
    /// Generated by the server (`Special`, `Media`).
    Virtual,
    /// Titles resolve through a resolver to entities (0029).
    Resolver,
}

/// One namespace.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct Namespace {
    /// Its number.
    pub id: i32,
    /// Its canonical name; empty for the main namespace.
    pub canonical: String,
    /// The local name every tenant shows, where it is not the canonical one (0095 §1).
    #[serde(default)]
    pub name: Option<String>,
    /// Whether it holds pages.
    pub kind: Kind,
    /// The models its pages may have.
    #[serde(default)]
    pub content_models: Vec<String>,
    /// The model a new page takes.
    #[serde(default)]
    pub default_model: Option<String>,
    /// The title normalizer (`first-letter`, `entity-id`, …).
    #[serde(default)]
    pub normalizer: Option<String>,
    /// What `meta=siteinfo` reports as its case.
    #[serde(default)]
    pub case: Option<String>,
    /// Whether `/` makes subpages.
    #[serde(default)]
    pub subpages: bool,
    /// Its talk namespace.
    #[serde(default)]
    pub talk: Option<i32>,
    /// The `site` setting that turns it on, while it is otherwise reserved.
    #[serde(default)]
    pub enabled_by: Option<String>,
}

impl Namespace {
    /// Whether its pages may have a model.
    #[must_use]
    pub fn allows_model(&self, model: &str) -> bool {
        self.content_models.iter().any(|m| m == model)
    }

    /// Whether it holds pages, given whether its enabling setting is on.
    #[must_use]
    pub fn holds_pages(&self, enabled: impl Fn(&str) -> bool) -> bool {
        self.kind == Kind::Pages && self.enabled_by.as_deref().is_none_or(enabled)
    }

    /// Whether its pages are entities (a `wikibase-*` or other entity model), whose links
    /// name the entity rather than a page: Item and Property by their ID, and the keyed
    /// types' namespaces (Domain, Keyword, Notation) by their key.
    #[must_use]
    pub fn is_entity_namespace(&self) -> bool {
        self.normalizer.as_deref() == Some("entity-id")
            || self
                .default_model
                .as_deref()
                .and_then(|m| scatter_pages::ContentModels::embedded().get(m))
                .is_some_and(|m| m.source == Some(scatter_pages::ModelSource::Entity))
    }

    /// The entity a title in this namespace names, by its ID: the title itself under the
    /// `entity-id` normalizer (`Q5`), `{keyed type}:{key}` in a keyed type's namespace
    /// (`domain:wikipedia.org`), whose normalizer is named for the type; `None` outside the
    /// entity namespaces.
    #[must_use]
    pub fn entity_id(&self, text: &str) -> Option<String> {
        if !self.is_entity_namespace() {
            return None;
        }
        match self.normalizer.as_deref() {
            Some("entity-id") | None => Some(text.to_string()),
            Some(keyed) => Some(format!("{keyed}:{text}")),
        }
    }
}

#[derive(Deserialize)]
struct File {
    namespace: Vec<Namespace>,
}

/// The registry.
#[derive(Debug, Clone)]
pub struct Namespaces {
    rows: Vec<Namespace>,
}

impl Namespaces {
    /// The embedded registry.
    ///
    /// # Panics
    ///
    /// If the embedded file does not parse, which its test rules out.
    #[must_use]
    pub fn embedded() -> &'static Namespaces {
        static R: OnceLock<Namespaces> = OnceLock::new();
        R.get_or_init(|| Self::parse(NAMESPACES_TOML).expect("the embedded registry parses"))
    }

    /// Parses a registry file.
    pub fn parse(text: &str) -> Result<Self, toml::de::Error> {
        let f: File = toml::from_str(text)?;
        Ok(Self { rows: f.namespace })
    }

    /// A namespace by number.
    #[must_use]
    pub fn get(&self, id: i32) -> Option<&Namespace> {
        self.rows.iter().find(|n| n.id == id)
    }

    /// A namespace by canonical name, ignoring case and treating `_` as a space.
    #[must_use]
    pub fn by_name(&self, name: &str) -> Option<&Namespace> {
        let want = name.replace('_', " ").trim().to_lowercase();
        self.rows
            .iter()
            .find(|n| n.canonical.to_lowercase() == want)
    }

    /// Every namespace, in registry order.
    pub fn iter(&self) -> impl Iterator<Item = &Namespace> {
        self.rows.iter()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_embedded_registry_parses() {
        let r = Namespaces::embedded();
        let project = r.get(PROJECT).expect("Project");
        assert_eq!(project.canonical, "Project");
        assert!(project.allows_model("wikitext"));
        assert!(project.holds_pages(|_| false));
        let template = r.get(TEMPLATE).expect("Template");
        assert!(
            template.holds_pages(|_| false),
            "templates are part of wikitext"
        );
        let module = r.get(828).expect("Module");
        assert!(!module.holds_pages(|_| false));
        assert!(module.holds_pages(|s| s == "wikitext.lua"));
        assert!(!r.get(3).expect("User talk").allows_model("wikitext"));
        assert!(r.get(120).expect("Item").is_entity_namespace());
        let domain = r.get(210).expect("Domain");
        assert!(
            domain.is_entity_namespace(),
            "a keyed type's pages are entities"
        );
        assert_eq!(
            domain.entity_id("wikipedia.org").as_deref(),
            Some("domain:wikipedia.org")
        );
        assert_eq!(r.get(120).unwrap().entity_id("Q5").as_deref(), Some("Q5"));
        assert_eq!(r.get(4).unwrap().entity_id("Home"), None);
        assert!(!r.get(4).unwrap().is_entity_namespace());
        assert_eq!(r.by_name("user_talk").map(|n| n.id), Some(3));
        let interface = r.get(8).unwrap();
        assert_eq!(interface.kind, Kind::Pages);
        assert_eq!(interface.canonical, "MediaWiki");
        assert_eq!(interface.name.as_deref(), Some("Interface"));
        assert_eq!(interface.talk, Some(9));
        // Help works as Project does, without its sprints and site styles (0096 §3).
        let help = r.get(12).expect("Help");
        assert_eq!(help.kind, Kind::Pages);
        assert_eq!(help.talk, Some(13));
        assert!(help.allows_model("wikitext"));
        assert!(!help.allows_model("triplespace-sprint"));
        assert!(!help.allows_model("sanitized-css"));
        assert!(!r.get(13).expect("Help talk").allows_model("wikitext"));
    }

    /// "`enabled_by`, where a namespace is implemented only while a tenant setting is on"
    /// (0008 §1).
    #[test]
    fn enabled_by_gates_whether_a_namespace_holds_pages() {
        let r = Namespaces::embedded();
        let gated = r
            .iter()
            .find(|n| n.enabled_by.is_some())
            .expect("the registry has an enabled_by namespace");
        assert!(
            !gated.holds_pages(|_| false),
            "reserved while its setting is off"
        );
        let setting = gated.enabled_by.as_deref().expect("from the find above");
        assert!(
            gated.holds_pages(|s| s == setting),
            "pages once its setting is on"
        );
    }

    /// A `resolver` namespace: "It holds no pages, so it has no model" (0008 §1).
    #[test]
    fn a_resolver_namespace_holds_no_pages_and_has_no_model() {
        let r = Namespaces::embedded();
        let resolver = r
            .iter()
            .find(|n| n.kind == Kind::Resolver)
            .expect("the registry has a resolver namespace");
        assert!(!resolver.holds_pages(|_| true));
        assert_eq!(resolver.default_model, None);
        assert!(resolver.content_models.is_empty());
    }

    /// "`Special` and `Media` (0039 §1) are virtual" (0008 §1).
    #[test]
    fn special_and_media_are_virtual() {
        let r = Namespaces::embedded();
        let special = r.by_name("special").expect("Special is in the registry");
        assert_eq!(special.kind, Kind::Virtual);
        assert!(!special.holds_pages(|_| true));
        let media = r.by_name("media").expect("Media is in the registry");
        assert_eq!(media.kind, Kind::Virtual);
        assert!(!media.holds_pages(|_| true));
    }

    /// claim 4: "Talk namespaces exist only for implemented subject namespaces, at the next odd number" (0008 §2).
    #[test]
    fn talk_namespaces_exist_only_for_implemented_subject_namespaces_at_the_next_odd_number() {
        let r = Namespaces::parse(NAMESPACES_TOML).expect("the embedded registry parses");
        for n in r.iter() {
            if let Some(talk) = n.talk {
                let t = r.get(talk).expect("the talk namespace is in the registry");
                assert_eq!(talk % 2, 1, "the talk number of {} is odd", n.canonical);
                assert_eq!(
                    talk,
                    n.id + 1,
                    "the talk number of {} is the next odd number",
                    n.canonical
                );
                if t.kind == Kind::Pages {
                    assert!(
                        t.allows_model("triplespace-talk"),
                        "the talk namespace of {} allows triplespace-talk",
                        n.canonical
                    );
                    assert_eq!(
                        t.default_model.as_deref(),
                        Some("triplespace-talk"),
                        "the talk namespace of {} defaults to triplespace-talk",
                        n.canonical
                    );
                } else {
                    assert!(
                        matches!(t.kind, Kind::Virtual | Kind::Reserved),
                        "the talk namespace of {} is virtual or reserved",
                        n.canonical
                    );
                }
            }
        }
    }

    /// claim 24: "Every talk namespace of kind `pages` has the single model `triplespace-talk`, which is also its default" (0008 §2).
    #[test]
    fn every_talk_namespace_of_kind_pages_has_the_single_model_triplespace_talk() {
        let r = Namespaces::parse(NAMESPACES_TOML).expect("the embedded registry parses");
        for talk in r
            .iter()
            .filter(|n| n.canonical.ends_with(" talk") && n.kind == Kind::Pages)
        {
            assert_eq!(
                talk.content_models,
                vec!["triplespace-talk".to_string()],
                "{} allows only triplespace-talk",
                talk.canonical
            );
            assert_eq!(
                talk.default_model.as_deref(),
                Some("triplespace-talk"),
                "{} defaults to triplespace-talk",
                talk.canonical
            );
        }
    }

    /// claim 7: "A resolver's talk number is `reserved`" (0008 §2).
    #[test]
    fn a_resolvers_talk_number_is_reserved() {
        let r = Namespaces::parse(NAMESPACES_TOML).expect("the embedded registry parses");
        for n in r.iter().filter(|n| n.kind == Kind::Resolver) {
            let talk = n.talk.expect("a resolver namespace has a talk number");
            let t = r
                .get(talk)
                .expect("the resolver's talk namespace is in the registry");
            assert_eq!(
                t.kind,
                Kind::Reserved,
                "the talk namespace of {} is reserved",
                n.canonical
            );
            assert!(
                !t.holds_pages(|_| true),
                "the talk namespace of {} holds no pages",
                n.canonical
            );
        }
    }

    /// claim 33: "Thread, Board and Domain do not allow subpages; Template, Module, Table, Query and Scope do; namespace 0 does not (§3.3); Project does (§3.5)" (0008 §2).
    #[test]
    fn subpage_flags_match_the_catalogue() {
        let r = Namespaces::parse(NAMESPACES_TOML).expect("the embedded registry parses");
        for id in [214, 310, 210] {
            let n = r.get(id).expect("the namespace is in the registry");
            assert!(!n.subpages, "{} does not allow subpages", n.canonical);
        }
        for id in [10, 828, 218, 124, 312] {
            let n = r.get(id).expect("the registry has this namespace");
            assert!(n.subpages, "{} allows subpages", n.canonical);
        }
        assert!(!r.get(0).expect("the main namespace").subpages);
        assert!(r.get(4).expect("Project").subpages);
    }
}
