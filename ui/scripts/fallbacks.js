// The @font-face rules of each fallback layer (ADR 0093 §3), written from
// docs/registry/themes.toml into src/fallbacks/{name}.css, which Vite builds and
// triplespace-ui writes into the stylesheet of every type set that names the layer.
//
// Each rule is Fontsource's own, for the subsets the registry lists and nothing else, so a
// face covers only the ranges no earlier family in the stack has, and woff2 only, which
// every browser that honours unicode-range reads. Run `npm run fallbacks` after changing a
// layer; src/fallbacks.test.js fails while the files are stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';

const ui = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const registry = join( ui, '../docs/registry/themes.toml' );

/**
 * The Fontsource package of a family: `Noto Sans Symbols 2` is `noto-sans-symbols-2`.
 *
 * @param {string} family
 * @return {string}
 */
export function packageName( family ) {
	return family.toLowerCase().replace( / /g, '-' );
}

/**
 * The fallback layers the registry defines, by name.
 *
 * @return {Object<string, {font: Array<{family: string, weights: number[], subsets: string[]}>}>}
 */
export function layers() {
	return parse( readFileSync( registry, 'utf8' ) ).fallback || {};
}

/**
 * A layer's stylesheet.
 *
 * @param {string} name
 * @param {{font: Array<{family: string, weights: number[], subsets: string[]}>}} layer
 * @return {string}
 */
export function layerCss( name, layer ) {
	const out = [
		`/* The typefaces of the fallback layer \`${ name }\` (docs/registry/themes.toml; ADR 0093).`,
		'   Generated by scripts/fallbacks.js: do not edit. SIL Open Font License 1.1. */',
		''
	];
	for ( const font of layer.font ) {
		const pkg = packageName( font.family );
		for ( const weight of font.weights ) {
			const file = join( ui, 'node_modules/@fontsource', pkg, `${ weight }.css` );
			// eslint-disable-next-line security/detect-non-literal-fs-filename
			const css = readFileSync( file, 'utf8' );
			for ( const subset of font.subsets ) {
				const marker = `/* ${ pkg }-${ subset }-${ weight }-normal */`;
				const at = css.indexOf( marker );
				if ( at < 0 ) {
					throw new Error( `${ font.family } ${ weight }: no subset ${ subset } in @fontsource/${ pkg }` );
				}
				const start = css.indexOf( '@font-face', at );
				const rule = css.slice( start, css.indexOf( '}', start ) + 1 )
					.replace( /,\s*url\([^)]*\.woff\) format\('woff'\)/, '' )
					.replace( /url\(\.\/files\//g, `url(../../node_modules/@fontsource/${ pkg }/files/` );
				if ( !rule.includes( `font-family: '${ font.family }';` ) || rule.includes( '.woff)' ) ) {
					throw new Error( `${ font.family } ${ weight } ${ subset }: unexpected rule` );
				}
				out.push( marker, rule, '' );
			}
		}
	}
	return out.join( '\n' );
}

/**
 * Where a layer's stylesheet lives.
 *
 * @param {string} name
 * @return {string}
 */
export function layerPath( name ) {
	return join( ui, 'src/fallbacks', `${ name }.css` );
}

if ( process.argv[ 1 ] === fileURLToPath( import.meta.url ) ) {
	for ( const [ name, layer ] of Object.entries( layers() ) ) {
		// eslint-disable-next-line security/detect-non-literal-fs-filename
		writeFileSync( layerPath( name ), layerCss( name, layer ) );
	}
}
